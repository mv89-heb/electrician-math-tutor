export function lessonForUnit(subjectId: string, unitId: string): LessonContent | undefined {
  const key = `${subjectId}/${unitId}`;
  const authored = authoredLessons[key];
  if (authored) return authored;

  const subject = getSubjectById(subjectId);
  const unit: SubjectUnit | undefined = getSubjectUnit(subjectId, unitId);
  if (!subject || !unit) return undefined;

  return {
    title: `מבוא: ${unit.title}`,
    explanation: unit.description,
    example: `נבחן את הנושא "${unit.title}" בהקשר של ${subject.title}. נזהה את המושגים, נבין את תפקידם במערכת ונקשר אותם לנושאים המקצועיים הסמוכים.`,
    checkQuestion: `מהו מוקד הלימוד המרכזי ביחידה "${unit.title}"?`,
    choices: [unit.title, subject.title, "נושא שאינו קשור ליחידה"],
    correctChoice: 0,
    feedback: `נכון. היחידה "${unit.title}" מתמקדת בנושא שהוגדר בתוכנית הלימוד. בהמשך יש להרחיב את המבוא לשיעורים מלאים ולתרגול מקצועי.`,
    safetyNote: subject.categoryId === "safety" || subject.categoryId === "installations"
      ? "זהו תוכן עיוני בלבד. עבודה מעשית מחייבת הכשרה, הרשאה, ציוד מתאים והשגחה מוסמכת."
      : undefined,
  };
}
